#!/usr/bin/env node
// Runs before `next build`/`next dev`:
//  1. regenerates src/generated/rates-index.ts from data/rates/<year>.json (year rollover = drop a new file in)
//  2. runs legal:extract if data/legal/legal-texts.json is absent
import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = process.cwd();
const years = readdirSync(join(root, 'data/rates'))
  .map((f) => /^(\d{4})\.json$/.exec(f)?.[1])
  .filter(Boolean)
  .sort();
if (!years.length) {
  console.error('prebuild: no data/rates/<year>.json files found');
  process.exit(1);
}
mkdirSync(join(root, 'src/generated'), { recursive: true });
const lines = [
  '// GENERATED by scripts/prebuild.mjs — do not edit. Add data/rates/<year>.json to roll over.',
  "import type { RatesFile } from '@/lib/rates';",
  ...years.map((y) => `import r${y} from '../../data/rates/${y}.json';`),
  `export const RATES_BY_YEAR: Record<number, RatesFile> = {`,
  ...years.map((y) => `  ${y}: r${y} as unknown as RatesFile,`),
  '};',
  '',
];
writeFileSync(join(root, 'src/generated/rates-index.ts'), lines.join('\n'));
console.log(`prebuild: rates index → ${years.join(', ')}`);

if (!existsSync(join(root, 'data/legal/legal-texts.json'))) {
  console.log('prebuild: legal-texts.json missing → running legal:extract');
  const r = spawnSync('node', ['scripts/extract-legal.mjs'], { stdio: 'inherit' });
  if (r.status !== 0) process.exit(r.status ?? 1);
}
